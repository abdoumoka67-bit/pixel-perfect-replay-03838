const DICTIONARIES: Record<LanguageCode, Dictionary> = { ar, fr, en };

/** Returns the text for `key` in `lang` (falls back to Arabic), filling `{name}` placeholders. */
export function translate(
  lang: LanguageCode,
  key: TranslationKey,
  vars?: Record<string, string | number>,
): string {
  const template = DICTIONARIES[lang][key] ?? ar[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}

/** "3 أيام" / "3 jours" / "1 day" in the chosen language. */
export function formatDays(lang: LanguageCode, n: number): string {
  return n === 1 ? translate(lang, "common.oneDay") : translate(lang, "common.days", { n });
}

/** Keys that exist in Arabic but are missing in another language (used by tests). */
export function missingTranslations(lang: LanguageCode): TranslationKey[] {
  return (Object.keys(ar) as TranslationKey[]).filter((k) => !DICTIONARIES[lang][k]);
}
