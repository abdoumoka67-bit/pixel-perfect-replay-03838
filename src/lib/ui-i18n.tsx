/** Translates an Arabic UI string into `language`, falling back to Arabic. */
export function tr(language: LanguageCode, text: string, vars?: Vars): string {
  const template =
    language === "ar" ? text : language === "fr" ? (fr[text] ?? text) : (en[text] ?? text);
  return applyVars(template, vars);
}

const UiLanguageContext = createContext<LanguageCode>("ar");

/** Provides the dashboard/storefront language to nested components. */
export function UiLanguageProvider({
  language,
  children,
}: {
  language: LanguageCode;
  children: ReactNode;
}) {
  return <UiLanguageContext.Provider value={language}>{children}</UiLanguageContext.Provider>;
}

export function useUiLanguage(): LanguageCode {
  return useContext(UiLanguageContext);
}

/** Returns a translator bound to the current dashboard/storefront language. */
export function useTr() {
  const language = useUiLanguage();
  return useCallback(
    (text: string, vars?: Vars) => tr(language, text, vars),
    [language],
  );
}

/**
 * Messages returned by server functions embed runtime values, so an exact
 * dictionary lookup is not enough. These patterns rebuild the template key
 * that lives in the dictionaries above.
 */
const SERVER_MESSAGE_PATTERNS: ReadonlyArray<{
  re: RegExp;
  template: string;
  vars: (match: RegExpMatchArray) => Vars;
}> = [
  {
    re: /^تعذر الاتصال \(رمز (.+)\)\.$/,
    template: "تعذر الاتصال (رمز {code}).",
    vars: (m) => ({ code: m[1] ?? "" }),
  },
  {
    re: /^سجل CNAME لا يشير بعد إلى (.+)$/,
    template: "سجل CNAME لا يشير بعد إلى {target}",
    vars: (m) => ({ target: m[1] ?? "" }),
  },
  {
    re: /^أنشأت Yalidine الطرد برقم التتبع (.+)، لكن تعذر حفظه في الطلب\. لا تعِد الإرسال\.$/,
    template:
      "أنشأت Yalidine الطرد برقم التتبع {tracking}، لكن تعذر حفظه في الطلب. لا تعِد الإرسال.",
    vars: (m) => ({ tracking: m[1] ?? "" }),
  },
];

/** Translates a server-generated message, keeping unknown text unchanged. */
export function trMessage(language: LanguageCode, message: string | null | undefined): string {
  if (!message) return "";
  const exact = tr(language, message);
  if (exact !== message) return exact;
  for (const { re, template, vars } of SERVER_MESSAGE_PATTERNS) {
    const match = message.match(re);
    if (match) return tr(language, template, vars(match));
  }
  return message;
}

/** Returns a translator for server-generated messages in the current language. */
export function useTranslatedMessage() {
  const language = useUiLanguage();
  return useCallback(
    (message: string | null | undefined) => trMessage(language, message),
    [language],
  );
}
