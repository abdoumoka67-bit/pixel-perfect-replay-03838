/**
 * UI text translations for the dashboard and storefronts.
 *
 * Arabic is the source text used inside the components, so adding a string is
 * just `t("نص عربي")`: if a translation is missing we fall back to Arabic
 * instead of showing a raw key. This complements `src/lib/i18n.ts`, which
 * holds the public marketing/auth copy.
 */

type Vars = Record<string, string | number>;

function applyVars(template: string, vars?: Vars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    vars[key] === undefined ? match : String(vars[key]),
  );
}

